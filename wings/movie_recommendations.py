import re

from .base import ask_ai, pick_genre, safe

NAME = "movie_recommendations"


def generate() -> str:
    genre = pick_genre()
    prompt = f"""رشّح 3 أفلام أو مسلسلات حقيقية وشهيرة جداً من نوع «{genre}».

الشروط الصارمة:
- اختر فقط أعمالاً عالمية مشهورة جداً تعرفها بيقين، مع سنة الإصدار الصحيحة.
- لا تذكر أسماء ممثلين أو مخرجين أو أماكن أو أحداثاً محددة من القصة.
- اكتب لكل عمل جملة واحدة فقط تصف أجواءه وسبب استحقاقه للمشاهدة (مزاج، أسلوب، إحساس).
- بدون حرق.
- التنسيق حرفياً:
1. الاسم (السنة): الجملة
2. الاسم (السنة): الجملة
3. الاسم (السنة): الجملة
"""
    raw = ask_ai(prompt, temperature=0.6, max_tokens=500)
    # سطر فارغ قبل كل رقم لتفصل الأعمال
    raw = re.sub(r"\s*(?=\b[123]\.\s)", "\n\n", raw).strip()
    return (
        f"🍿 <b>ترشيحات اليوم: {safe(genre)}</b>\n\n"
        f"{safe(raw)}\n\n#ترشيحات_أفلام"
    )
